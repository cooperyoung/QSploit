ROOT = Path(__file__).resolve().parents[1]
FIXTURES = ROOT / 'tests/fixtures'
DEMO = ROOT / 'qsploit/demo'
NAMES = ('tls12-rsa-aes256','tls12-rsa-aes256-noems')
HEADERS = {'X-QSploit':'1'}


def evidence(name):
    wire = (FIXTURES / f'{name}.pcap').read_bytes()
    expected = json.loads((FIXTURES / f'{name}.expected.json').read_text())
    capture = read_connections(wire)
    assert len(capture.connections) == 1
    session = parse_tls(capture.connections[0])
    pair = json.loads((DEMO / 'factors.json').read_text())[expected['rsa_modulus_hex']]
    factors = RSAFactors(int(pair['p'],16),int(pair['q'],16))
    return wire,expected,session,factors


def protected_indices(session):
    active = {'c2s':False,'s2c':False}
    for index,record in enumerate(session.records):
        if record.content_type == 20:
            active[record.direction] = True
        elif active[record.direction]:
            yield index


@pytest.mark.parametrize('name',NAMES)
def test_aes256_independent_capture_oracles_and_full_http(name):
    wire,expected,session,factors = evidence(name)
    assert hashlib.sha256(wire).hexdigest() == expected['sha256']
    assert (DEMO / f'{name}.pcap').read_bytes() == wire
    assert expected['cipher'] == 'AES256-GCM-SHA384'
    assert expected['cipher_suite_id'] == 157
    assert expected['prf_hash'] == 'sha384'
    assert expected['server_shutdown_complete']
    assert session.tls_version == 0x0303 and session.cipher_suite == 0x009d
    assert session.kex == 'rsa_transport' and not session.blockers
    assert session.ems is (name == 'tls12-rsa-aes256')
    assert problem_for(session).n == int(expected['rsa_modulus_hex'],16)
    master = derive_master_secret(session,factors)
    assert master.hex() == expected['master_secret_hex']
    assert len(derive_key_block(master,session.client_random,session.server_random,0x009d)) == 72
    recovered = decrypt_tls12(session,factors)
    assert recovered.client_finished_verified and recovered.server_finished_verified
    assert recovered.client_close_notify and recovered.server_close_notify
    assert recovered.authenticated_records == 19
    assert recovered.c2s == base64.b64decode(expected['c2s_base64'])
    assert recovered.s2c == base64.b64decode(expected['s2c_base64'])
    assert hashlib.sha256(recovered.c2s).hexdigest() == expected['endpoint_observations']['server_received_sha256']
    assert hashlib.sha256(recovered.s2c).hexdigest() == expected['endpoint_observations']['client_received_sha256']
    messages = parse_http(recovered)
    assert len(messages) == 2
    for message,oracle in zip(messages,expected['exchanges']):
        assert message.view.request.raw_b64 == oracle['request_base64']
        assert message.view.response.raw_b64 == oracle['response_base64']
    assert messages[1].view.response.decoded_body_b64 == expected['json_body_base64']


@pytest.mark.parametrize('name',NAMES)
def test_aes256_all_protected_records_authenticate_including_finished_and_alerts(name):
    _,_,session,factors = evidence(name)
    for index in protected_indices(session):
        records = list(session.records)
        original = records[index]
        records[index] = replace(original,fragment=original.fragment[:-1]+bytes([original.fragment[-1]^1]))
        with pytest.raises(QSploitError) as error:
            decrypt_tls12(replace(session,records=tuple(records)),factors)
        assert error.value.code == 'AEAD_AUTH_FAILED'


@pytest.mark.parametrize('name',NAMES)
def test_aes256_wrong_factors_and_wrong_schedule_fail_closed(name):
    _,_,session,factors = evidence(name)
    with pytest.raises(QSploitError) as error:
        decrypt_tls12(session,RSAFactors(factors.p+2,factors.q))
    assert error.value.code == 'INVALID_FACTOR_PAIR'
    for modified in (replace(session,ems=not session.ems),replace(session,cipher_suite=0x009c)):
        with pytest.raises(QSploitError) as error:
            decrypt_tls12(modified,factors)
        assert error.value.code == 'AEAD_AUTH_FAILED'


def altered_capture(wire,missing=False):
    """Synthetic fault injection into a genuine capture; not a bundled demo."""
    source = dpkt.pcap.Reader(io.BytesIO(wire))
    output = io.BytesIO()
    writer = dpkt.pcap.Writer(output,linktype=source.datalink(),snaplen=262144)
    changed = False
    for timestamp,packet in source:
        ip = dpkt.loopback.Loopback(packet).data
        tcp = ip.data
        if not changed and isinstance(tcp,dpkt.tcp.TCP) and tcp.data[:1] == b'\x17':
            changed = True
            if missing:
                continue
            tcp.data = tcp.data[:-1]+bytes([tcp.data[-1]^1])
            packet = packet[:4]+bytes(ip)
        writer.writepkt(packet,timestamp)
    assert changed
    return output.getvalue()


