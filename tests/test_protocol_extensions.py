def upload(client,wire):
    result = client.post('/api/captures',content=wire,headers=HEADERS)
    assert result.status_code == 201,result.text
    return result.json()['sessions'][0]


def recover(client,sid):
    started = client.post(f'/api/sessions/{sid}/recover',json={},headers=HEADERS)
    assert started.status_code == 202,started.text
    deadline = time.monotonic()+12
    while time.monotonic() < deadline:
        result = client.get(f"/api/jobs/{started.json()['id']}").json()
        if result['state'] in {'succeeded','failed','timed_out'}:
            return result
        time.sleep(.025)
    pytest.fail('Recovery worker exceeded bounded test deadline')


def no_plaintext(client,sid):
    for endpoint in ('http','http/0','http/0/preview','application/c2s','application/s2c'):
        response = client.get(f'/api/sessions/{sid}/{endpoint}')
        assert response.status_code == 409
        assert response.json()['error']['code'] == 'NOT_READY'


@pytest.mark.parametrize('name',NAMES)
def test_aes256_api_upload_recover_and_actual_selected_inspector(client,name):
    wire,expected,_,_ = evidence(name)
    session = upload(client,wire)
    sid = session['id']
    assert session['cipher_suite_name'] == 'TLS_RSA_WITH_AES_256_GCM_SHA384'
    assert session['recovery_modes'] == ['fixture']
    assert session['implementation'] == 'supported'
    no_plaintext(client,sid)
    job = recover(client,sid)
    assert job['state'] == 'succeeded',job
    assert job['method'] == 'fixture_lookup' and job['execution'] == 'none'
    assert job['demo_factors'] is None and not job['provider_job_ids']
    assert job['client_finished_verified'] and job['server_finished_verified']
    assert job['authenticated_records'] == 19
    messages = client.get(f'/api/sessions/{sid}/http').json()
    assert [(message['method'],message['status']) for message in messages] == [('GET',200),('POST',200)]
    for index,oracle in enumerate(expected['exchanges']):
        actual = client.get(f'/api/sessions/{sid}/http/{index}').json()
        assert actual['request']['raw_b64'] == oracle['request_base64']
        assert actual['response']['raw_b64'] == oracle['response_base64']
    assert actual['response']['decoded_body_b64'] == expected['json_body_base64']
    assert ['note','hello world'] in actual['form_parameters']
    preview = client.get(f'/api/sessions/{sid}/http/0/preview')
    assert preview.status_code == 200
    assert 'Welcome back, Cooper.' in preview.text
    assert '<script' not in preview.text and 'untrusted.qsploit.test' not in preview.text
    assert "default-src 'none'" in preview.headers['content-security-policy']
    assert 'sandbox;' in preview.headers['content-security-policy']
    for direction in ('c2s','s2c'):
        assert client.get(f'/api/sessions/{sid}/application/{direction}').content == base64.b64decode(expected[f'{direction}_base64'])
    assert expected['master_secret_hex'] not in json.dumps(job)


@pytest.mark.parametrize('name',NAMES)
def test_aes256_corrupt_packet_reaches_authentication_failure_without_plaintext(client,name):
    wire,_,_,_ = evidence(name)
    session = upload(client,altered_capture(wire))
    job = recover(client,session['id'])
    assert job['state'] == 'failed' and job['error']['code'] == 'AEAD_AUTH_FAILED'
    no_plaintext(client,session['id'])


@pytest.mark.parametrize('name',NAMES)
def test_aes256_missing_packet_blocks_recovery_without_plaintext(client,name):
    wire,_,_,_ = evidence(name)
    session = upload(client,altered_capture(wire,missing=True))
    assert not session['recovery_modes']
    assert 'TCP_GAP' in [issue['code'] for issue in session['blockers']]
    response = client.post(f"/api/sessions/{session['id']}/recover",json={},headers=HEADERS)
    assert response.status_code == 400
    assert response.json()['error']['code'] == 'TCP_GAP'
    no_plaintext(client,session['id'])


def test_aes256_invalid_recovery_factor_pair_never_publishes_plaintext(client,monkeypatch):
    wire,_,_,factors = evidence(NAMES[0])
    async def wrong_factors(problem,options,report):
        return Recovery(RSAFactors(factors.p+2,factors.q),'fixture_lookup','none',None,())
    monkeypatch.setattr('qsploit.app.run_recovery',wrong_factors)
    session = upload(client,wire)
    job = recover(client,session['id'])
    assert job['state'] == 'failed' and job['error']['code'] == 'INVALID_FACTOR_PAIR'
    assert not job['factor_pair_verified']
    no_plaintext(client,session['id'])
